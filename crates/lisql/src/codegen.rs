//! Translate validated operators into readable Rust, with no Lisql interpreter
//! at runtime.

use crate::{
    diagnostic::Diagnostic,
    ir::{Expr, ExprKind, OpKind, Query, Type},
};
use lisql_runtime::{Dialect, Value};
use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use std::collections::BTreeSet;

/// Generate and format callable Rust functions from checked query values.
pub(crate) fn generate(queries: &[Query], dialect: Dialect) -> Result<String, Diagnostic> {
    let mut functions = TokenStream::new();

    for query in queries {
        let name = format_ident!("{}", query.rust_name);
        let args = query.params.iter().map(|p| {
            let name = format_ident!("{}", p.rust_name);
            let ty = match p.ty {
                Type::I32 => quote!(i32),
                Type::I64 => quote!(i64),
                Type::Bool => quote!(bool),
                Type::String => quote!(&str),
                Type::Unknown => unreachable!(),
            };
            quote!(#name: #ty)
        });

        // Sorted imports keep output deterministic and include only the types
        // actually used.
        let mut imports = BTreeSet::from(["Pipeline", "Op", "Dialect"]);
        let mut steps = Vec::new();

        for op in &query.ops {
            // Keep source ranges attached to IR until the last compiler pass.
            debug_assert!(op.span.start >= query.span.start);
            let step = match &op.kind {
                OpKind::From(table) => quote!(Op::From(#table)),
                OpKind::Select(columns) => quote!(Op::Select(::std::vec![#(#columns),*])),
                OpKind::Where(expr) => {
                    let expr = expression(expr, query, &mut imports);
                    quote!(Op::Where(#expr))
                }
                OpKind::OrderBy(items) => {
                    imports.insert("Direction");
                    let items = items.iter().map(|(name, dir)| {
                        let dir = format_ident!("{dir:?}");
                        quote!((#name, Direction::#dir))
                    });
                    quote!(Op::OrderBy(::std::vec![#(#items),*]))
                }
                OpKind::Limit(expr) | OpKind::Offset(expr) => {
                    let value = value(expr, query, &mut imports);
                    if matches!(op.kind, OpKind::Limit(_)) {
                        quote!(Op::Limit(#value))
                    } else {
                        quote!(Op::Offset(#value))
                    }
                }
            };
            steps.push(step);
        }

        let imports = imports.into_iter().map(|name| format_ident!("{name}"));
        let documentation = format!(
            " Builds a {} SQL template and owned, ordered bindings.",
            dialect.name()
        );
        let dialect = format_ident!("{dialect:?}");
        functions.extend(quote! {
            #[doc = #documentation]
            #[doc = " Does not execute the query."]
            pub fn #name(#(#args),*) -> ::std::result::Result<::lisql_runtime::Query, ::lisql_runtime::BuildError> {
                use ::lisql_runtime::{#(#imports),*};
                Pipeline::new() #(.then(#steps))* .build(Dialect::#dialect)
            }
        });
    }

    // Parse the generated tokens before formatting; source strings are always
    // quoted literals.
    let file = syn::parse2::<syn::File>(functions)
        .map_err(|e| Diagnostic::new(0..0, format!("internal code generation error: {e}")))?;

    // prettyplease normalizes whitespace. Restore the two intentional visual
    // boundaries in our generated layout: between query functions and after
    // each local import.
    let formatted = prettyplease::unparse(&file)
        .replace("\n/// Builds", "\n\n/// Builds")
        .replace(";\n    Pipeline::new()", ";\n\n    Pipeline::new()");

    Ok(format!(
        "// Generated by lisql {}. Dialect: {}.\n// Regenerate from the .lisql source; manual edits will be overwritten.\n\n{}",
        env!("CARGO_PKG_VERSION"),
        dialect.name(),
        formatted
    ))
}

/// Emit runtime expression constructors and collect their required imports.
fn expression(expr: &Expr, query: &Query, imports: &mut BTreeSet<&'static str>) -> TokenStream {
    imports.insert("Expr");

    match &expr.kind {
        ExprKind::Column(name) => quote!(Expr::column(#name)),
        ExprKind::Literal(_) | ExprKind::Param(_) => {
            let v = value(expr, query, imports);
            quote!(Expr::value(#v))
        }
        ExprKind::Compare(op, left, right) => {
            imports.insert("Compare");
            let op = format_ident!("{op:?}");
            let left = expression(left, query, imports);
            let right = expression(right, query, imports);
            quote!(Expr::compare(Compare::#op, #left, #right))
        }
        ExprKind::And(items) | ExprKind::Or(items) => {
            let name = if matches!(expr.kind, ExprKind::And(_)) {
                format_ident!("and")
            } else {
                format_ident!("or")
            };
            let items: Vec<_> = items
                .iter()
                .map(|e| expression(e, query, imports))
                .collect();
            quote!(Expr::#name(::std::vec![#(#items),*]))
        }
        ExprKind::Not(item) | ExprKind::IsNull(item) | ExprKind::IsNotNull(item) => {
            let name = match expr.kind {
                ExprKind::Not(_) => "not",
                ExprKind::IsNull(_) => "is_null",
                _ => "is_not_null",
            };
            let name = format_ident!("{name}");
            let item = expression(item, query, imports);
            quote!(Expr::#name(#item))
        }
    }
}

/// Emit a literal or parameter binding; other expression forms are excluded by
/// checking.
fn value(expr: &Expr, query: &Query, imports: &mut BTreeSet<&'static str>) -> TokenStream {
    imports.insert("Value");

    // Each occurrence creates its own binding. Copy strings so results outlive
    // caller input.
    match &expr.kind {
        ExprKind::Param(index) => {
            let param = &query.params[*index];
            let name = format_ident!("{}", param.rust_name);
            match param.ty {
                Type::I32 => quote!(Value::I32(#name)),
                Type::I64 => quote!(Value::I64(#name)),
                Type::Bool => quote!(Value::Bool(#name)),
                Type::String => quote!(Value::String(::std::string::String::from(#name))),
                Type::Unknown => unreachable!(),
            }
        }
        ExprKind::Literal(value) => match value {
            Value::I32(v) => quote!(Value::I32(#v)),
            Value::I64(v) => quote!(Value::I64(#v)),
            Value::Bool(v) => quote!(Value::Bool(#v)),
            Value::String(v) => quote!(Value::String(::std::string::String::from(#v))),
        },
        _ => unreachable!("semantic analysis restricts pagination to parameters and constants"),
    }
}
